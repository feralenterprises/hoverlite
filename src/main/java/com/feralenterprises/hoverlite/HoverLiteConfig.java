package com.feralenterprises.hoverlite;

import net.runelite.client.config.Config;
import net.runelite.client.config.ConfigGroup;
import net.runelite.client.config.ConfigItem;
import net.runelite.client.config.ConfigSection;

@ConfigGroup("hoverlite")
public interface HoverLiteConfig extends Config
{
    @ConfigSection(name = "Hover display", description = "Choose what to show under the mouse for each type of target", position = 0)
    String DISPLAY = "display";

    @ConfigSection(name = "Behavior", description = "Tooltip safety and convenience options", position = 1)
    String BEHAVIOR = "behavior";

    @ConfigItem(keyName = "npcMode", name = "NPCs", description = "For example, Feed instead of Feed Duke Sucellus (level-758)", position = 0, section = DISPLAY)
    default HoverMode npcMode() { return HoverMode.ACTION_ONLY; }

    @ConfigItem(keyName = "inventoryMode", name = "Inventory / item panels", description = "Keep item names visible while hovering inventory or bank items", position = 1, section = DISPLAY)
    default HoverMode inventoryMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "objectMode", name = "World objects", description = "Doors, poll booths, altars, etc.", position = 2, section = DISPLAY)
    default HoverMode objectMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "groundMode", name = "Ground items", description = "Items lying on the ground", position = 3, section = DISPLAY)
    default HoverMode groundMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "playerMode", name = "Players", description = "Actions on other players", position = 4, section = DISPLAY)
    default HoverMode playerMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "interfaceMode", name = "Interface buttons", description = "Non-item widgets such as buttons and tabs", position = 5, section = DISPLAY)
    default HoverMode interfaceMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "otherMode", name = "Other actions", description = "Unclassified game actions", position = 6, section = DISPLAY)
    default HoverMode otherMode() { return HoverMode.FULL; }

    @ConfigItem(keyName = "hideTrivial", name = "Ignore trivial actions", description = "Don't show hover text for Walk here, Cancel, Continue, or sliding puzzle Move", position = 0, section = BEHAVIOR)
    default boolean hideTrivial() { return true; }

    @ConfigItem(keyName = "respectNative", name = "Respect built-in tooltips", description = "Avoid drawing on top of tooltips generated by the game itself", position = 1, section = BEHAVIOR)
    default boolean respectNative() { return true; }
}
